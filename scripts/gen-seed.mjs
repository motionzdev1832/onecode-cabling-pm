import { writeFileSync } from 'node:fs'
import { project, scopeItems, tasks } from './seed-data.mjs'

const q = (v) => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number') return String(v)
  return "'" + String(v).replace(/'/g, "''") + "'"
}

const lines = []
lines.push('-- Seed: project, scope list and baseline plan. Generated by scripts/gen-seed.mjs')
lines.push(
  `INSERT INTO project (id, name, client, location, planned_start, planned_finish, notes) VALUES (${q(project.id)}, ${q(project.name)}, ${q(project.client)}, ${q(project.location)}, ${q(project.plannedStart)}, ${q(project.plannedFinish)}, ${q(project.notes)});`,
)
lines.push('--> statement-breakpoint')
scopeItems.forEach((s, i) => {
  lines.push(
    `INSERT INTO scope_items (id, code, name, category, unit, total_qty, sort_order) VALUES (${i + 1}, ${q(s.code)}, ${q(s.name)}, ${q(s.category)}, ${q(s.unit)}, ${q(s.totalQty)}, ${i + 1});`,
  )
  lines.push('--> statement-breakpoint')
})
tasks.forEach((t, i) => {
  const [id, parentId, level, isSummary, floor, duration, start, finish, name] = t
  lines.push(
    `INSERT INTO tasks (id, parent_id, name, level, is_summary, floor, duration_days, planned_start, planned_finish, sort_order) VALUES (${id}, ${q(parentId)}, ${q(name)}, ${level}, ${isSummary}, ${q(floor)}, ${duration}, ${q(start)}, ${q(finish)}, ${i + 1});`,
  )
  lines.push('--> statement-breakpoint')
})
writeFileSync(new URL('../drizzle/0001_seed.sql', import.meta.url), lines.join('\n') + '\n')
console.log(`wrote drizzle/0001_seed.sql: ${scopeItems.length} scope items, ${tasks.length} tasks`)
